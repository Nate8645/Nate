'use strict';

const fs = require('fs');
const crypto = require('crypto');
const path = require('path');

const envPath = path.join(process.cwd(), '.env');

function parseEnv(text) {
  const values = {};
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#') || !trimmed.includes('=')) continue;
    const index = trimmed.indexOf('=');
    const key = trimmed.slice(0, index);
    const value = trimmed.slice(index + 1);
    values[key] = value;
  }
  return values;
}

const existing = fs.existsSync(envPath) ? parseEnv(fs.readFileSync(envPath, 'utf8')) : {};
const defaults = {
  NODE_ENV: 'development',
  HOST: '0.0.0.0',
  PORT: '3000',
  APP_URL: 'http://localhost:3000',
  APP_NAME: 'UltraLaunch AI',
  SESSION_SECRET: crypto.randomBytes(32).toString('hex'),
  DATABASE_PATH: 'data/ultralaunch.sqlite',
  ADMIN_EMAILS: 'founder@example.com',
  SUPPORT_EMAIL: 'support@example.com',
  AI_PROVIDER: 'openai',
  OPENAI_API_KEY: '',
  OPENAI_BASE_URL: 'https://api.openai.com/v1',
  OPENAI_MODEL: 'gpt-4o-mini',
  STRIPE_SECRET_KEY: '',
  STRIPE_WEBHOOK_SECRET: '',
  STRIPE_PRICE_STARTER: '',
  STRIPE_PRICE_PRO: '',
  STRIPE_PRICE_BUSINESS: '',
  STRIPE_PRICE_PILOT: '',
  STRIPE_PORTAL_RETURN_URL: '',
};

const lines = [
  '# UltraLaunch AI local environment',
  '# Generated by npm run env:prepare. Secrets are intentionally not committed.',
  '# Fill STRIPE_SECRET_KEY and STRIPE_WEBHOOK_SECRET yourself; never paste them into chat.',
  '',
];
for (const [key, fallback] of Object.entries(defaults)) {
  const value = existing[key] !== undefined && existing[key] !== '' ? existing[key] : fallback;
  lines.push(`${key}=${value}`);
}
lines.push('');

fs.writeFileSync(envPath, lines.join('\n'), { mode: 0o600 });
fs.mkdirSync(path.join(process.cwd(), 'data'), { recursive: true });
console.log(`Prepared ${envPath}`);
console.log('Filled safe defaults and generated SESSION_SECRET. Stripe/OpenAI keys remain blank for you to set securely.');
